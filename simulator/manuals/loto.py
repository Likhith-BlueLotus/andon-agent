@dataclass(frozen=True)
class EnergySource:
    kind: str  # electrical, hydraulic, pneumatic, gravity, spring, thermal, ...
    source: str  # where it comes from and its magnitude
    isolating_device: str
    stored: str  # residual/stored energy after isolation and how it is controlled


@dataclass(frozen=True)
class LotoStep:
    phase: str
    cfr: str  # paragraph of 29 CFR 1910.147, e.g. "(d)(3)"
    text: str  # one short imperative sentence; quoted verbatim everywhere

    @property
    def citation(self) -> str:
        return f"{CFR}{self.cfr}"


@dataclass(frozen=True)
class LotoProcedure:
    doc: str
    equipment: str
    applies_to: tuple[str, ...]
    purpose: str
    authorised: str
    energy: tuple[EnergySource, ...]
    steps: tuple[LotoStep, ...]


def _t(asset_id: str, tag: str) -> plant.TagSpec:
    return plant.tag_spec(asset_id, tag)


def _g(x: float | None) -> str:
    assert x is not None
    return f"{x:g}"


